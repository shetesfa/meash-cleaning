class MeashI18n {
    constructor() {
        this.lang = localStorage.getItem('meash_lang') || 'am';
    }

    setLanguage(lang) {
        if (meashTranslations[lang]) {
            this.lang = lang;
            localStorage.setItem('meash_lang', lang);
            this.updateDom();
            window.dispatchEvent(new CustomEvent('meash-lang-changed', { detail: lang }));
        }
    }

    getLanguage() {
        return this.lang;
    }

    t(key) {
        return meashTranslations[this.lang][key] || meashTranslations['en'][key] || key;
    }

    updateDom() {
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            const translation = this.t(key);
            if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
                if (el.placeholder) el.placeholder = translation;
            } else {
                el.innerText = translation;
            }
        });

        document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
            const key = el.getAttribute('data-i18n-placeholder');
            el.placeholder = this.t(key);
        });
    }
}

window.meashI18n = new MeashI18n();
