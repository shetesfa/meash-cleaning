    errBox.classList.add('hidden');
    btn.disabled = true;
    btnText.innerText = 'በማረጋገጥ ላይ...';

    try {
      const res = await fetch('/api/auth/login', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json', 'Accept': 'application/json' },
        body: JSON.stringify({
          login: roleSelect.value,
          password: pwdInput.value,
        })
      });

      let data = null;
      try {
        data = await res.json();
      } catch (jsonErr) {
        data = null;
