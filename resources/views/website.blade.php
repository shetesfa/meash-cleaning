        btn.classList.add('bg-teal', 'text-white');
        setTimeout(() => {
          window.location.href = '/app';
        }, 300);
      } else {
        errBox.classList.remove('hidden');
        let errorMsg = 'የተሳሳተ የይለፍ ቃል ነው፤ እባክዎ በትክክል ያስገቡ!';
        if (res.status === 429) {
